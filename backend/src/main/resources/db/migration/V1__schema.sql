-- Esquema inicial da plataforma EduFin.
-- SQL portável entre PostgreSQL (produção) e H2 em modo PostgreSQL (testes / perfil local).
-- Valores monetários: NUMERIC(14,2). Datas/horas: TIMESTAMP WITH TIME ZONE (UTC).

-- ============================== USUÁRIOS ==============================
CREATE TABLE users (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email             VARCHAR(254) NOT NULL,
    password_hash     VARCHAR(255) NOT NULL,
    display_name      VARCHAR(40)  NOT NULL,
    role              VARCHAR(20)  NOT NULL,
    enabled           BOOLEAN      NOT NULL DEFAULT TRUE,
    -- Renovado ao trocar senha, papel ou status: invalida sessões abertas anteriormente.
    security_stamp    VARCHAR(36)  NOT NULL,
    terms_accepted_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_login_at     TIMESTAMP WITH TIME ZONE,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    version           BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT uk_users_display_name UNIQUE (display_name),
    CONSTRAINT ck_users_role CHECK (role IN ('USER', 'EDUCATOR', 'MODERATOR', 'ADMIN'))
);

CREATE TABLE user_preferences (
    user_id              BIGINT      NOT NULL PRIMARY KEY,
    theme                VARCHAR(10) NOT NULL DEFAULT 'SYSTEM',
    notify_goals         BOOLEAN     NOT NULL DEFAULT TRUE,
    notify_learning      BOOLEAN     NOT NULL DEFAULT TRUE,
    notify_achievements  BOOLEAN     NOT NULL DEFAULT TRUE,
    notify_community     BOOLEAN     NOT NULL DEFAULT TRUE,
    weekly_lesson_target INT         NOT NULL DEFAULT 3,
    CONSTRAINT fk_pref_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_pref_theme CHECK (theme IN ('SYSTEM', 'LIGHT', 'DARK')),
    CONSTRAINT ck_pref_target CHECK (weekly_lesson_target BETWEEN 1 AND 50)
);

CREATE TABLE activity_logs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL,
    type        VARCHAR(40)  NOT NULL,
    description VARCHAR(255) NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_activity_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);
CREATE INDEX ix_activity_user_created ON activity_logs (user_id, created_at);

CREATE TABLE password_reset_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    used_at    TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_reset_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uk_reset_token UNIQUE (token_hash)
);

-- ============================== METAS ==============================
CREATE TABLE goals (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT        NOT NULL,
    title         VARCHAR(80)   NOT NULL,
    description   VARCHAR(500),
    category      VARCHAR(30)   NOT NULL,
    target_amount NUMERIC(14, 2) NOT NULL,
    deadline      DATE,
    status        VARCHAR(20)   NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at  TIMESTAMP WITH TIME ZONE,
    cancelled_at  TIMESTAMP WITH TIME ZONE,
    version       BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT fk_goal_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_goal_target CHECK (target_amount > 0),
    CONSTRAINT ck_goal_status CHECK (status IN ('ACTIVE', 'COMPLETED', 'CANCELLED'))
);
CREATE INDEX ix_goal_user_status ON goals (user_id, status);

CREATE TABLE goal_movements (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    goal_id    BIGINT         NOT NULL,
    type       VARCHAR(20)    NOT NULL,
    amount     NUMERIC(14, 2) NOT NULL,
    note       VARCHAR(200),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_gmov_goal FOREIGN KEY (goal_id) REFERENCES goals (id) ON DELETE CASCADE,
    CONSTRAINT ck_gmov_amount CHECK (amount > 0),
    CONSTRAINT ck_gmov_type CHECK (type IN ('CONTRIBUTION', 'WITHDRAWAL'))
);
CREATE INDEX ix_gmov_goal_created ON goal_movements (goal_id, created_at);

-- ============================== TRANSAÇÕES ==============================
CREATE TABLE transactions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT         NOT NULL,
    description VARCHAR(120)   NOT NULL,
    amount      NUMERIC(14, 2) NOT NULL,
    type        VARCHAR(10)    NOT NULL,
    category    VARCHAR(30)    NOT NULL,
    occurred_on DATE           NOT NULL,
    notes       VARCHAR(500),
    origin      VARCHAR(20)    NOT NULL,
    goal_id     BIGINT,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_tx_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_tx_goal FOREIGN KEY (goal_id) REFERENCES goals (id) ON DELETE SET NULL,
    CONSTRAINT ck_tx_amount CHECK (amount > 0),
    CONSTRAINT ck_tx_type CHECK (type IN ('INCOME', 'EXPENSE')),
    CONSTRAINT ck_tx_origin CHECK (origin IN ('MANUAL', 'SIMULATED', 'EXTERNAL'))
);
CREATE INDEX ix_tx_user_date ON transactions (user_id, occurred_on);

-- ============================== CALCULADORA ==============================
CREATE TABLE simulations (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT         NOT NULL,
    name           VARCHAR(80)    NOT NULL,
    interest_type  VARCHAR(10)    NOT NULL,
    principal      NUMERIC(14, 2) NOT NULL,
    rate_percent   NUMERIC(9, 4)  NOT NULL,
    rate_unit      VARCHAR(10)    NOT NULL,
    period         INT            NOT NULL,
    period_unit    VARCHAR(10)    NOT NULL,
    contribution   NUMERIC(14, 2) NOT NULL,
    final_amount   NUMERIC(16, 2) NOT NULL,
    total_invested NUMERIC(16, 2) NOT NULL,
    total_interest NUMERIC(16, 2) NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_sim_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);
CREATE INDEX ix_sim_user ON simulations (user_id, created_at);

-- ============================== QUIZZES ==============================
CREATE TABLE quizzes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(120) NOT NULL,
    description VARCHAR(500) NOT NULL,
    category    VARCHAR(30)  NOT NULL,
    difficulty  VARCHAR(15)  NOT NULL,
    published   BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_quiz_difficulty CHECK (difficulty IN ('BEGINNER', 'INTERMEDIATE', 'ADVANCED'))
);

CREATE TABLE quiz_questions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id     BIGINT        NOT NULL,
    position    INT           NOT NULL,
    statement   VARCHAR(500)  NOT NULL,
    explanation VARCHAR(1000) NOT NULL,
    topic       VARCHAR(30)   NOT NULL,
    CONSTRAINT fk_question_quiz FOREIGN KEY (quiz_id) REFERENCES quizzes (id) ON DELETE CASCADE,
    CONSTRAINT uk_question_position UNIQUE (quiz_id, position)
);

CREATE TABLE quiz_options (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id BIGINT       NOT NULL,
    position    INT          NOT NULL,
    text        VARCHAR(300) NOT NULL,
    correct     BOOLEAN      NOT NULL,
    CONSTRAINT fk_option_question FOREIGN KEY (question_id) REFERENCES quiz_questions (id) ON DELETE CASCADE,
    CONSTRAINT uk_option_position UNIQUE (question_id, position)
);

CREATE TABLE quiz_attempts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL,
    quiz_id         BIGINT       NOT NULL,
    status          VARCHAR(15)  NOT NULL,
    started_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at     TIMESTAMP WITH TIME ZONE,
    total_questions INT          NOT NULL,
    correct_count   INT,
    score           INT,
    percent         NUMERIC(5, 2),
    CONSTRAINT fk_attempt_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_attempt_quiz FOREIGN KEY (quiz_id) REFERENCES quizzes (id),
    CONSTRAINT ck_attempt_status CHECK (status IN ('IN_PROGRESS', 'COMPLETED'))
);
CREATE INDEX ix_attempt_user ON quiz_attempts (user_id, started_at);

CREATE TABLE quiz_attempt_answers (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id  BIGINT  NOT NULL,
    question_id BIGINT  NOT NULL,
    option_id   BIGINT  NOT NULL,
    correct     BOOLEAN NOT NULL,
    answered_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_answer_attempt FOREIGN KEY (attempt_id) REFERENCES quiz_attempts (id) ON DELETE CASCADE,
    CONSTRAINT fk_answer_question FOREIGN KEY (question_id) REFERENCES quiz_questions (id),
    CONSTRAINT fk_answer_option FOREIGN KEY (option_id) REFERENCES quiz_options (id),
    CONSTRAINT uk_answer_once UNIQUE (attempt_id, question_id)
);

-- ============================== CURSOS ==============================
CREATE TABLE courses (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug              VARCHAR(80)   NOT NULL,
    title             VARCHAR(120)  NOT NULL,
    summary           VARCHAR(300)  NOT NULL,
    description       VARCHAR(2000) NOT NULL,
    objectives        VARCHAR(2000) NOT NULL,
    category          VARCHAR(30)   NOT NULL,
    difficulty        VARCHAR(15)   NOT NULL,
    estimated_minutes INT           NOT NULL,
    position          INT           NOT NULL,
    published         BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_course_slug UNIQUE (slug),
    CONSTRAINT ck_course_difficulty CHECK (difficulty IN ('BEGINNER', 'INTERMEDIATE', 'ADVANCED'))
);

CREATE TABLE course_modules (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT       NOT NULL,
    position  INT          NOT NULL,
    title     VARCHAR(120) NOT NULL,
    CONSTRAINT fk_module_course FOREIGN KEY (course_id) REFERENCES courses (id) ON DELETE CASCADE,
    CONSTRAINT uk_module_position UNIQUE (course_id, position)
);

CREATE TABLE lessons (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id         BIGINT         NOT NULL,
    position          INT            NOT NULL,
    title             VARCHAR(120)   NOT NULL,
    content           VARCHAR(20000) NOT NULL,
    estimated_minutes INT            NOT NULL,
    quiz_id           BIGINT,
    CONSTRAINT fk_lesson_module FOREIGN KEY (module_id) REFERENCES course_modules (id) ON DELETE CASCADE,
    CONSTRAINT fk_lesson_quiz FOREIGN KEY (quiz_id) REFERENCES quizzes (id) ON DELETE SET NULL,
    CONSTRAINT uk_lesson_position UNIQUE (module_id, position)
);

CREATE TABLE enrollments (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT NOT NULL,
    course_id      BIGINT NOT NULL,
    enrolled_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at   TIMESTAMP WITH TIME ZONE,
    last_lesson_id BIGINT,
    CONSTRAINT fk_enroll_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_enroll_course FOREIGN KEY (course_id) REFERENCES courses (id) ON DELETE CASCADE,
    CONSTRAINT fk_enroll_lesson FOREIGN KEY (last_lesson_id) REFERENCES lessons (id) ON DELETE SET NULL,
    CONSTRAINT uk_enroll UNIQUE (user_id, course_id)
);

CREATE TABLE lesson_progress (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT NOT NULL,
    lesson_id    BIGINT NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_lprog_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_lprog_lesson FOREIGN KEY (lesson_id) REFERENCES lessons (id) ON DELETE CASCADE,
    CONSTRAINT uk_lprog UNIQUE (user_id, lesson_id)
);

CREATE TABLE lesson_notes (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT        NOT NULL,
    lesson_id  BIGINT        NOT NULL,
    content    VARCHAR(5000) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_note_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_note_lesson FOREIGN KEY (lesson_id) REFERENCES lessons (id) ON DELETE CASCADE,
    CONSTRAINT uk_note UNIQUE (user_id, lesson_id)
);

CREATE TABLE course_reviews (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL,
    course_id  BIGINT       NOT NULL,
    rating     INT          NOT NULL,
    comment    VARCHAR(1000),
    hidden     BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_review_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_review_course FOREIGN KEY (course_id) REFERENCES courses (id) ON DELETE CASCADE,
    CONSTRAINT uk_review UNIQUE (user_id, course_id),
    CONSTRAINT ck_review_rating CHECK (rating BETWEEN 1 AND 5)
);

-- ============================== GAMIFICAÇÃO ==============================
CREATE TABLE point_events (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT       NOT NULL,
    event_type    VARCHAR(30)  NOT NULL,
    reference_key VARCHAR(60)  NOT NULL,
    points        INT          NOT NULL,
    description   VARCHAR(200) NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_points_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uk_points_once UNIQUE (user_id, event_type, reference_key),
    CONSTRAINT ck_points_positive CHECK (points >= 0)
);
CREATE INDEX ix_points_user_created ON point_events (user_id, created_at);

CREATE TABLE achievements (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(40)  NOT NULL,
    title       VARCHAR(80)  NOT NULL,
    description VARCHAR(255) NOT NULL,
    icon        VARCHAR(30)  NOT NULL,
    points      INT          NOT NULL,
    CONSTRAINT uk_achievement_code UNIQUE (code)
);

CREATE TABLE user_achievements (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT NOT NULL,
    achievement_id BIGINT NOT NULL,
    unlocked_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_uach_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_uach_achievement FOREIGN KEY (achievement_id) REFERENCES achievements (id) ON DELETE CASCADE,
    CONSTRAINT uk_uach UNIQUE (user_id, achievement_id)
);

-- ============================== NOTIFICAÇÕES ==============================
CREATE TABLE notifications (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL,
    type       VARCHAR(30)  NOT NULL,
    title      VARCHAR(120) NOT NULL,
    message    VARCHAR(500) NOT NULL,
    link       VARCHAR(200),
    dedup_key  VARCHAR(120),
    read_at    TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_notif_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uk_notif_dedup UNIQUE (user_id, dedup_key)
);
CREATE INDEX ix_notif_user_created ON notifications (user_id, created_at);

-- ============================== COMUNIDADE ==============================
CREATE TABLE forum_posts (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id  BIGINT        NOT NULL,
    category   VARCHAR(30)   NOT NULL,
    title      VARCHAR(140)  NOT NULL,
    body       VARCHAR(5000) NOT NULL,
    status     VARCHAR(15)   NOT NULL,
    edited     BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_post_author FOREIGN KEY (author_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_post_status CHECK (status IN ('VISIBLE', 'HIDDEN', 'REMOVED'))
);
CREATE INDEX ix_post_status_created ON forum_posts (status, created_at);

CREATE TABLE forum_comments (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id    BIGINT        NOT NULL,
    author_id  BIGINT        NOT NULL,
    body       VARCHAR(2000) NOT NULL,
    status     VARCHAR(15)   NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_comment_post FOREIGN KEY (post_id) REFERENCES forum_posts (id) ON DELETE CASCADE,
    CONSTRAINT fk_comment_author FOREIGN KEY (author_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_comment_status CHECK (status IN ('VISIBLE', 'HIDDEN', 'REMOVED'))
);
CREATE INDEX ix_comment_post ON forum_comments (post_id, created_at);

CREATE TABLE forum_likes (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id    BIGINT NOT NULL,
    user_id    BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_like_post FOREIGN KEY (post_id) REFERENCES forum_posts (id) ON DELETE CASCADE,
    CONSTRAINT fk_like_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uk_like UNIQUE (post_id, user_id)
);

CREATE TABLE forum_reports (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id BIGINT       NOT NULL,
    post_id     BIGINT,
    comment_id  BIGINT,
    reason      VARCHAR(30)  NOT NULL,
    details     VARCHAR(500),
    status      VARCHAR(15)  NOT NULL,
    resolved_by BIGINT,
    resolved_at TIMESTAMP WITH TIME ZONE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_report_reporter FOREIGN KEY (reporter_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_report_post FOREIGN KEY (post_id) REFERENCES forum_posts (id) ON DELETE CASCADE,
    CONSTRAINT fk_report_comment FOREIGN KEY (comment_id) REFERENCES forum_comments (id) ON DELETE CASCADE,
    CONSTRAINT fk_report_resolver FOREIGN KEY (resolved_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uk_report_post UNIQUE (reporter_id, post_id),
    CONSTRAINT uk_report_comment UNIQUE (reporter_id, comment_id),
    CONSTRAINT ck_report_target CHECK ((post_id IS NULL AND comment_id IS NOT NULL) OR (post_id IS NOT NULL AND comment_id IS NULL)),
    CONSTRAINT ck_report_status CHECK (status IN ('OPEN', 'RESOLVED', 'DISMISSED'))
);
CREATE INDEX ix_report_status ON forum_reports (status, created_at);

-- ============================== CARTEIRAS SIMULADAS ==============================
CREATE TABLE wallets (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT        NOT NULL,
    name               VARCHAR(60)   NOT NULL,
    description        VARCHAR(300),
    assumed_annual_rate NUMERIC(7, 4) NOT NULL,
    archived           BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_wallet_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_wallet_rate CHECK (assumed_annual_rate >= 0 AND assumed_annual_rate <= 100)
);
CREATE INDEX ix_wallet_user ON wallets (user_id);

CREATE TABLE wallet_movements (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wallet_id        BIGINT         NOT NULL,
    type             VARCHAR(20)    NOT NULL,
    amount           NUMERIC(14, 2) NOT NULL,
    occurred_on      DATE           NOT NULL,
    note             VARCHAR(200),
    reference_period VARCHAR(7),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_wmov_wallet FOREIGN KEY (wallet_id) REFERENCES wallets (id) ON DELETE CASCADE,
    CONSTRAINT ck_wmov_amount CHECK (amount >= 0),
    CONSTRAINT ck_wmov_type CHECK (type IN ('INITIAL', 'DEPOSIT', 'WITHDRAWAL', 'SIMULATED_RETURN')),
    CONSTRAINT uk_wmov_return_period UNIQUE (wallet_id, reference_period)
);
CREATE INDEX ix_wmov_wallet_date ON wallet_movements (wallet_id, occurred_on);

-- ============================== FEEDBACK ==============================
CREATE TABLE feedback (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT,
    type           VARCHAR(20)   NOT NULL,
    subject        VARCHAR(120)  NOT NULL,
    message        VARCHAR(2000) NOT NULL,
    status         VARCHAR(15)   NOT NULL,
    admin_response VARCHAR(1000),
    handled_by     BIGINT,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_feedback_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_feedback_handler FOREIGN KEY (handled_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT ck_feedback_type CHECK (type IN ('SUGGESTION', 'PROBLEM', 'EXPERIENCE')),
    CONSTRAINT ck_feedback_status CHECK (status IN ('NEW', 'IN_REVIEW', 'RESOLVED', 'ARCHIVED'))
);
CREATE INDEX ix_feedback_status ON feedback (status, created_at);
